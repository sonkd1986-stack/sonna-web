CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  price NUMERIC(12, 2) NOT NULL,
  image_url TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT products_title_valid
    CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
  CONSTRAINT products_price_valid
    CHECK (price BETWEEN 0 AND 9999999999.99),
  CONSTRAINT products_image_url_valid
    CHECK (image_url ~* '^https?://')
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conrelid = 'public.products'::regclass
      AND conname = 'products_title_valid'
  ) THEN
    ALTER TABLE public.products
      ADD CONSTRAINT products_title_valid
      CHECK (char_length(btrim(title)) BETWEEN 1 AND 200);
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conrelid = 'public.products'::regclass
      AND conname = 'products_price_valid'
  ) THEN
    ALTER TABLE public.products
      ADD CONSTRAINT products_price_valid
      CHECK (price BETWEEN 0 AND 9999999999.99);
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conrelid = 'public.products'::regclass
      AND conname = 'products_image_url_valid'
  ) THEN
    ALTER TABLE public.products
      ADD CONSTRAINT products_image_url_valid
      CHECK (image_url ~* '^https?://');
  END IF;
END
$$;

CREATE INDEX IF NOT EXISTS products_created_at_idx
  ON public.products (created_at DESC);

ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
